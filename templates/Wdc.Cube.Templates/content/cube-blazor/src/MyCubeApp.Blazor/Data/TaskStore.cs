using System.Globalization;
using MyCubeApp.Domain;
using Npgsql;
using Wdc.Domain;
using Wdc.Persistence;
using Wdc.Persistence.PostgreSql;

namespace MyCubeApp.Blazor.Data;

/// <summary>
/// The database: opens it on a schema, creates the table and a few tasks when the table is missing, and hands out the
/// repository.
/// </summary>
public sealed class TaskStore : IAsyncDisposable
{
    private readonly NpgsqlDataSource _dataSource;

    private TaskStore(NpgsqlDataSource dataSource, Database database)
    {
        _dataSource = dataSource;
        Database = database;
        Tasks = new TaskRepository(database);
    }

    public Database Database { get; }

    public ITaskRepository Tasks { get; }

    /// <param name="connectionString">An Npgsql connection string.</param>
    /// <param name="schema">Letters, digits and underscores: it goes into the DDL as it is.</param>
    public static TaskStore Open(string connectionString, string schema, Microsoft.Extensions.Logging.ILogger? logger = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);
        if (string.IsNullOrEmpty(schema) || !schema.All(c => char.IsAsciiLetterOrDigit(c) || c == '_'))
        {
            throw new ArgumentException($"Not a schema name: '{schema}'.", nameof(schema));
        }

        var dataSource = NpgsqlDataSource.Create(connectionString);
        return new TaskStore(dataSource, PostgreSql.CreateDatabase(dataSource, schema, logger));
    }

    /// <summary>Creates the schema, the table and a few tasks, unless the table already exists.</summary>
    /// <returns>Whether they were created.</returns>
    public async Task<bool> EnsureCreated(CancellationToken cancellationToken = default)
    {
        var s = Database.Schema!;
        var tables = await Database.Scalar(new SqlStatement(
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = @p0 AND table_name = 'task'", [s]),
            cancellationToken);
        if (Convert.ToInt64(tables, CultureInfo.InvariantCulture) > 0)
        {
            return false;
        }

        await Database.Required(async _ =>
        {
            await Database.Execute(new SqlStatement($"CREATE SCHEMA IF NOT EXISTS \"{s}\"", []), cancellationToken);
            await Database.Execute(new SqlStatement($"""
                CREATE TABLE "{s}".task (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title text NOT NULL,
                    done boolean NOT NULL DEFAULT false)
                """, []), cancellationToken);
            foreach (var (title, done) in s_firstTasks)
            {
                await Tasks.Insert(new TaskItem { Title = title, Done = done }, cancellationToken: cancellationToken);
            }
        }, cancellationToken);
        return true;
    }

    /// <summary>Drops the schema with everything in it (the tests' throwaway schemas).</summary>
    public Task Drop(CancellationToken cancellationToken = default) =>
        Database.Execute(new SqlStatement($"DROP SCHEMA IF EXISTS \"{Database.Schema}\" CASCADE", []), cancellationToken);

    public ValueTask DisposeAsync() => _dataSource.DisposeAsync();

    private static readonly (string Title, bool Done)[] s_firstTasks =
    [
        ("Run the application", true),
        ("Open a task, rename it and save", false),
        ("Add a field to the task, from the database to the view", false),
    ];
}
