using System.Data.Common;
using Microsoft.Data.SqlClient;
using Npgsql;
using Wdc.Persistence.PostgreSql;

namespace Wdc.Persistence.Tests;

/// <summary>
/// One schema per test run, created and dropped by the fixture (decision D-14). Without the connection string in the
/// environment the tests are skipped, saying why.
/// </summary>
public abstract class DatabaseFixture : IAsyncLifetime
{
    protected DatabaseFixture(string variable)
    {
        Variable = variable;
        ConnectionString = Environment.GetEnvironmentVariable(variable);
        Schema = "wdc_test_" + Guid.NewGuid().ToString("N")[..10];
    }

    public string Variable { get; }

    public string? ConnectionString { get; }

    public string Schema { get; }

    public Shopping? Shopping { get; private set; }

    public string SkipReason => $"{Variable} is not set (run: source scripts/test-env.sh)";

    /// <summary>
    /// Whether a read outside a transaction sees the last committed state instead of waiting for its locks (MVCC).
    /// Always in PostgreSQL; in SQL Server only with READ_COMMITTED_SNAPSHOT on.
    /// </summary>
    public virtual Task<bool> ReadsDoNotWaitForWriters() => Task.FromResult(true);

    public async ValueTask InitializeAsync()
    {
        if (ConnectionString is null)
        {
            return;
        }

        Shopping = new Shopping(await CreateDatabase());
        await ExecuteScript(CreateSchemaScript());
    }

    public async ValueTask DisposeAsync()
    {
        if (ConnectionString is not null)
        {
            await ExecuteScript(DropSchemaScript());
            await DisposeDatabase();
        }

        GC.SuppressFinalize(this);
    }

    /// <summary>Empties every table, children first.</summary>
    public Task Reset() => ExecuteScript(
        [.. new[] { "purchase_item", "purchase", "user_account", "product" }.Select(t => $"DELETE FROM {Qualified(t)}")]);

    public async Task ExecuteScript(IEnumerable<string> statements)
    {
        await using var connection = await OpenConnection();
        foreach (var sql in statements)
        {
            await using var command = connection.CreateCommand();
            command.CommandText = sql;
            await command.ExecuteNonQueryAsync();
        }
    }

    protected abstract Task<Database> CreateDatabase();

    protected abstract Task DisposeDatabase();

    protected abstract Task<DbConnection> OpenConnection();

    protected abstract IEnumerable<string> CreateSchemaScript();

    protected abstract IEnumerable<string> DropSchemaScript();

    protected abstract string Qualified(string table);
}

public sealed class PostgreSqlFixture() : DatabaseFixture("WDC_TEST_POSTGRES")
{
    private NpgsqlDataSource? _dataSource;

    protected override Task<Database> CreateDatabase()
    {
        _dataSource = NpgsqlDataSource.Create(ConnectionString!);
        return Task.FromResult(PostgreSql.PostgreSql.CreateDatabase(_dataSource, Schema));
    }

    protected override async Task DisposeDatabase()
    {
        if (_dataSource is not null)
        {
            await _dataSource.DisposeAsync();
        }
    }

    protected override async Task<DbConnection> OpenConnection() => await _dataSource!.OpenConnectionAsync();

    protected override string Qualified(string table) => $"\"{Schema}\".\"{table}\"";

    protected override IEnumerable<string> CreateSchemaScript() =>
    [
        $"CREATE SCHEMA \"{Schema}\"",
        $"""
         CREATE TABLE {Qualified("product")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             name varchar(200) NOT NULL,
             price numeric(12, 2),
             description text,
             image bytea)
         """,
        $"""
         CREATE TABLE {Qualified("user_account")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             user_name varchar(100) NOT NULL UNIQUE,
             password varchar(100),
             name varchar(200),
             role varchar(20) NOT NULL DEFAULT 'Customer')
         """,
        $"""
         CREATE TABLE {Qualified("purchase")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             buy_date timestamptz NOT NULL DEFAULT now(),
             user_id bigint REFERENCES {Qualified("user_account")} (id))
         """,
        $"""
         CREATE TABLE {Qualified("purchase_item")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             purchase_id bigint NOT NULL REFERENCES {Qualified("purchase")} (id),
             product_id bigint REFERENCES {Qualified("product")} (id),
             amount integer NOT NULL,
             price numeric(12, 2) NOT NULL)
         """,
    ];

    protected override IEnumerable<string> DropSchemaScript() => [$"DROP SCHEMA \"{Schema}\" CASCADE"];
}

public sealed class SqlServerFixture() : DatabaseFixture("WDC_TEST_SQLSERVER")
{
    public override async Task<bool> ReadsDoNotWaitForWriters()
    {
        await using var connection = await OpenConnection();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT is_read_committed_snapshot_on FROM sys.databases WHERE name = DB_NAME()";
        return Convert.ToBoolean(await command.ExecuteScalarAsync(), System.Globalization.CultureInfo.InvariantCulture);
    }

    protected override Task<Database> CreateDatabase() =>
        Task.FromResult(SqlServer.SqlServer.CreateDatabase(ConnectionString!, Schema));

    protected override Task DisposeDatabase()
    {
        SqlConnection.ClearAllPools();
        return Task.CompletedTask;
    }

    protected override async Task<DbConnection> OpenConnection()
    {
        var connection = new SqlConnection(ConnectionString);
        await connection.OpenAsync();
        return connection;
    }

    protected override string Qualified(string table) => $"[{Schema}].[{table}]";

    protected override IEnumerable<string> CreateSchemaScript() =>
    [
        $"CREATE SCHEMA [{Schema}]",
        $"""
         CREATE TABLE {Qualified("product")} (
             id bigint IDENTITY(1, 1) PRIMARY KEY,
             name nvarchar(200) NOT NULL,
             price decimal(12, 2) NULL,
             description nvarchar(max) NULL,
             image varbinary(max) NULL)
         """,
        $"""
         CREATE TABLE {Qualified("user_account")} (
             id bigint IDENTITY(1, 1) PRIMARY KEY,
             user_name nvarchar(100) NOT NULL UNIQUE,
             password nvarchar(100) NULL,
             name nvarchar(200) NULL,
             role nvarchar(20) NOT NULL DEFAULT 'Customer')
         """,
        $"""
         CREATE TABLE {Qualified("purchase")} (
             id bigint IDENTITY(1, 1) PRIMARY KEY,
             buy_date datetimeoffset NOT NULL DEFAULT SYSDATETIMEOFFSET(),
             user_id bigint NULL REFERENCES {Qualified("user_account")} (id))
         """,
        $"""
         CREATE TABLE {Qualified("purchase_item")} (
             id bigint IDENTITY(1, 1) PRIMARY KEY,
             purchase_id bigint NOT NULL REFERENCES {Qualified("purchase")} (id),
             product_id bigint NULL REFERENCES {Qualified("product")} (id),
             amount int NOT NULL,
             price decimal(12, 2) NOT NULL)
         """,
    ];

    // No CASCADE in SQL Server: tables first (children first), then the schema.
    protected override IEnumerable<string> DropSchemaScript() =>
    [
        .. new[] { "purchase_item", "purchase", "user_account", "product" }.Select(t => $"DROP TABLE IF EXISTS {Qualified(t)}"),
        $"DROP SCHEMA [{Schema}]",
    ];
}
