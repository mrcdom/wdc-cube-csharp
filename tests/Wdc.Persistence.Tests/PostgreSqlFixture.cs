using System.Data.Common;
using Npgsql;

namespace Wdc.Persistence.Tests;

public class PostgreSqlFixture() : DatabaseFixture("WDC_TEST_POSTGRES")
{
    private NpgsqlDataSource? _dataSource;

    protected override Task<Database> CreateDatabase()
    {
        _dataSource = NpgsqlDataSource.Create(ConnectionString!);
        return Task.FromResult(PostgreSql.PostgreSql.CreateDatabase(_dataSource, Schema));
    }

    protected override async Task DisposeDatabase()
    {
        if (_dataSource is not null)
        {
            await _dataSource.DisposeAsync();
        }
    }

    protected override async Task<DbConnection> OpenConnection() => await _dataSource!.OpenConnectionAsync();

    protected override string Qualified(string table) => $"\"{Schema}\".\"{table}\"";

    protected override IEnumerable<string> CreateSchemaScript() =>
    [
        $"CREATE SCHEMA \"{Schema}\"",
        $"""
         CREATE TABLE {Qualified("product")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             name varchar(200) NOT NULL,
             price numeric(12, 2),
             description text,
             image bytea)
         """,
        $"""
         CREATE TABLE {Qualified("user_account")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             user_name varchar(100) NOT NULL UNIQUE,
             password varchar(100),
             name varchar(200),
             role varchar(20) NOT NULL DEFAULT 'Customer')
         """,
        $"""
         CREATE TABLE {Qualified("purchase")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             buy_date timestamptz NOT NULL DEFAULT now(),
             user_id bigint REFERENCES {Qualified("user_account")} (id))
         """,
        $"""
         CREATE TABLE {Qualified("purchase_item")} (
             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             purchase_id bigint NOT NULL REFERENCES {Qualified("purchase")} (id),
             product_id bigint REFERENCES {Qualified("product")} (id),
             amount integer NOT NULL,
             price numeric(12, 2) NOT NULL)
         """,
    ];

    protected override IEnumerable<string> DropSchemaScript() => [$"DROP SCHEMA \"{Schema}\" CASCADE"];
}
