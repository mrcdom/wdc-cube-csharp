using Wdc.Cube.Codec;

namespace Wdc.Cube.Tests.Codec;

/// <summary>The address codec (decision D-20): RFC 5297, the TypeScript version's addresses, and the envelope rules.</summary>
public sealed class AesHistoryCodecTests
{
    private static readonly byte[] s_key = [.. Enumerable.Range(0, 32).Select(i => (byte)i)];
    private static readonly byte[] s_key2 = [.. Enumerable.Range(0, 32).Select(i => (byte)(255 - i))];

    private static byte[] Hex(string hex) => Convert.FromHexString(hex.Replace(" ", "", StringComparison.Ordinal));

    [Fact]
    public void AesSiv_MatchesRfc5297_A1()
    {
        using var siv = new AesSiv(Hex("fffefdfc fbfaf9f8 f7f6f5f4 f3f2f1f0 f0f1f2f3 f4f5f6f7 f8f9fafb fcfdfeff"));
        byte[][] ad = [Hex("10111213 14151617 18191a1b 1c1d1e1f 20212223 24252627")];
        var plaintext = Hex("11223344 55667788 99aabbcc ddee");

        var sealedBytes = siv.Seal(ad, plaintext);

        Assert.Equal(Hex("85632d07 c6e8f37f 950acd32 0a2ecc93 40c02b96 90c4dc04 daef7f6a fe5c"), sealedBytes);
        Assert.Equal(plaintext, siv.Open(ad, sealedBytes));
    }

    // Generated by the TypeScript codec (wdc-cube/codec, @noble/ciphers 2.4.0) with key 00..1f (v1) and 1f..00
    // reversed bytes ff..e0 (v2, with v1 previous).
    public static TheoryData<string, string, string> TypeScriptAddresses => new()
    {
        { "v1", "state=todo&page=2", "AQCjRtWZy5B98I2Jf1ZQoC5sD9yjrxh6nGFgxivEc0WrIyA" },
        { "v1", "a=1", "AQC6tNk4icimzkzIDoNh8Pz54g6N" },
        { "v1", "nome=Jos%C3%A9&cpf=12345678901", "AQBa4-iuHQt-1XxmsX_mZpbUO_qzUpGrGhGIzHGp5yZjkN8a0yZy_LN1iNIhrQCn" },
        { "v1", "", "AQBkahw-_rfSWJv90IksyGkj" },
        { "v2", "state=todo&page=2", "AgDgSoJ71cWazg0nTgZb_otyDBUr8cMN8qJwHQ5oLmKQNwg" },
    };

    private static AesHistoryCodec CodecFor(string which) => which == "v1"
        ? new AesHistoryCodec(s_key)
        : new AesHistoryCodec(new HistoryKeyVersion(2, s_key2), [new HistoryKeyVersion(1, s_key)]);

    [Theory]
    [MemberData(nameof(TypeScriptAddresses))]
    public void TypeScriptAddresses_OpenHere_AndTheSameStateSealsToTheSameAddress(string key, string query, string payload)
    {
        var codec = CodecFor(key);

        Assert.Equal(query, codec.Decode(payload));
        Assert.Equal(payload, codec.Encode(query));
    }

    [Fact]
    public void ADeflatedTypeScriptAddress_OpensHere()
    {
        var query = "q=" + string.Concat(Enumerable.Repeat("abcdefghij", 40));

        Assert.Equal(query, new AesHistoryCodec(s_key).Decode("AQGRPmpdmr9uarqMmAO10oxeAWS2eAGlsZiFotpFbvD_t5rm"));
    }

    [Fact]
    public void Compresses_OnlyWhenThatHelps_AndRoundTrips()
    {
        var codec = new AesHistoryCodec(s_key);
        var repetitive = "q=" + string.Concat(Enumerable.Repeat("abcdefghij", 40));

        Assert.Equal(0, Base64Url.Decode(codec.Encode("page=2")!)[1] & 1);
        Assert.Equal(1, Base64Url.Decode(codec.Encode(repetitive)!)[1] & 1);
        Assert.Equal(repetitive, codec.Decode(codec.Encode(repetitive)!));
    }

    [Fact]
    public void HidesWhatItCarries_InOneUrlSafeParameter()
    {
        var payload = new AesHistoryCodec(s_key).Encode("cpf=12345678901")!;

        Assert.DoesNotContain("12345678901", payload, StringComparison.Ordinal);
        Assert.Matches("^[A-Za-z0-9_-]+$", payload);
    }

    [Fact]
    public void Refuses_AnotherKey_AnAlteredAddress_AndWhatIsNotAnEnvelope()
    {
        var codec = new AesHistoryCodec(s_key);
        var payload = codec.Encode("state=todo")!;
        var bytes = Base64Url.Decode(payload);
        bytes[^1] ^= 1;

        Assert.Null(new AesHistoryCodec(s_key2).Decode(payload));
        Assert.Null(codec.Decode(Base64Url.Encode(bytes)));
        Assert.Null(codec.Decode("not-base64url!!"));
        Assert.Null(codec.Decode(""));
    }

    [Fact]
    public void Rotation_OpensThePreviousKey_SealsWithTheCurrent_RefusesWhatIsNoLongerOffered()
    {
        var before = new AesHistoryCodec(s_key);
        var after = new AesHistoryCodec(new HistoryKeyVersion(2, s_key2), [new HistoryKeyVersion(1, s_key)]);
        var narrowed = new AesHistoryCodec(new HistoryKeyVersion(2, s_key2), []);
        var old = before.Encode("state=todo&page=2")!;

        Assert.Equal("state=todo&page=2", after.Decode(old));
        Assert.Equal(2, Base64Url.Decode(after.Encode("state=todo")!)[0]);
        Assert.Null(before.Decode(after.Encode("state=todo")!));
        Assert.Null(narrowed.Decode(old));
    }

    [Fact]
    public void RefusesBadKeysAndVersions()
    {
        Assert.Throws<ArgumentException>(() => new AesHistoryCodec([1, 2, 3]));
        Assert.Throws<ArgumentException>(() => new AesHistoryCodec(new HistoryKeyVersion(0, s_key), []));
        Assert.Throws<ArgumentException>(() => new AesHistoryCodec(new HistoryKeyVersion(256, s_key), []));
        Assert.Throws<ArgumentException>(() =>
            new AesHistoryCodec(new HistoryKeyVersion(1, s_key), [new HistoryKeyVersion(1, s_key2)]));
        Assert.Equal(s_key, HistoryKeyVersion.FromText(1, Base64Url.Encode(s_key)).Key);
    }
}
