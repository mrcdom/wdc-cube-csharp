public enum DatabaseProvider
{
    PostgreSql,
    SqlServer,
}

/// <summary>
/// The Shopping database: picks the dialect, creates the schema and the demo data when the tables are missing, and
/// hands out the repositories.
/// </summary>
public sealed class ShoppingStore : IAsyncDisposable
{
    private readonly IAsyncDisposable? _owned;

    private ShoppingStore(DatabaseProvider provider, Database database, IAsyncDisposable? owned)
    {
        Provider = provider;
        Database = database;
        _owned = owned;
        var items = new PurchaseItemRepository(database);
        Repositories = new ShoppingRepositories(
            new UserRepository(database),
            new ProductRepository(database),
            new PurchaseRepository(database, items),
            items,
            database);
    }

    public DatabaseProvider Provider { get; }

    public Database Database { get; }

    public ShoppingRepositories Repositories { get; }

    public static ShoppingStore Open(DatabaseProvider provider, string connectionString, string schema, ILogger? logger = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);
        ArgumentException.ThrowIfNullOrWhiteSpace(schema);
        switch (provider)
        {
            case DatabaseProvider.PostgreSql:
                var dataSource = NpgsqlDataSource.Create(connectionString);
                return new ShoppingStore(provider, PostgreSql.CreateDatabase(dataSource, schema, logger), dataSource);
            case DatabaseProvider.SqlServer:
                return new ShoppingStore(provider, SqlServer.CreateDatabase(connectionString, schema, logger), null);
            default:
                throw new ArgumentOutOfRangeException(nameof(provider), provider, null);
        }
    }

    /// <summary>Creates the schema, the tables and the demo data, unless the tables already exist.</summary>
    /// <returns>Whether anything was created.</returns>
    public async Task<bool> EnsureCreated(CancellationToken cancellationToken = default)
    {
        var schema = Database.Schema!;
        var exists = await Database.Scalar(Statement(
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = @p0 AND table_name = 'product'", schema),
            cancellationToken);
        if (Convert.ToInt64(exists, System.Globalization.CultureInfo.InvariantCulture) > 0)
        {
            return false;
        }

        foreach (var ddl in ShoppingSchema.Create(Provider, schema))
        {
            await Database.Execute(Statement(ddl), cancellationToken);
        }

        await ShoppingDemoData.Load(Repositories, cancellationToken);
        return true;
    }

    /// <summary>Drops every table and the schema (tests).</summary>
    public async Task Drop(CancellationToken cancellationToken = default)
    {
        foreach (var ddl in ShoppingSchema.Drop(Provider, Database.Schema!))
        {
            await Database.Execute(Statement(ddl), cancellationToken);
        }
    }

    public async ValueTask DisposeAsync()
    {
        if (_owned is not null)
        {
            await _owned.DisposeAsync();
        }

        if (Provider == DatabaseProvider.SqlServer)
        {
            SqlConnection.ClearAllPools();
        }
    }

    private static SqlStatement Statement(string sql, params object?[] parameters) => new(sql, parameters);
}

/// <summary>The DDL of each database. Indexes back each named ordering.</summary>
internal static class ShoppingSchema
{
    private static readonly string[] s_tables = ["purchase_item", "purchase", "user_account", "product"];

    public static IEnumerable<string> Create(DatabaseProvider provider, string schema) =>
        provider == DatabaseProvider.PostgreSql ? PostgreSql(schema) : SqlServer(schema);

    public static IEnumerable<string> Drop(DatabaseProvider provider, string schema) =>
        provider == DatabaseProvider.PostgreSql
            ? [$"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE"]
            : [.. s_tables.Select(t => $"DROP TABLE IF EXISTS [{schema}].[{t}]"), $"DROP SCHEMA IF EXISTS [{schema}]"];

    private static IEnumerable<string> PostgreSql(string s)
    {
        yield return $"CREATE SCHEMA IF NOT EXISTS \"{s}\"";
        yield return $"""
            CREATE TABLE "{s}".product (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name text NOT NULL,
                price numeric(20, 2) NOT NULL,
                description text NOT NULL,
                image bytea)
            """;
        yield return $"CREATE INDEX ix_product_name ON \"{s}\".product (name)";
        yield return $"CREATE INDEX ix_product_price ON \"{s}\".product (price)";
        yield return $"""
            CREATE TABLE "{s}".user_account (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_name varchar(255) NOT NULL UNIQUE,
                password varchar(255) NOT NULL,
                name varchar(255) NOT NULL,
                roles varchar(255))
            """;
        yield return $"CREATE INDEX ix_user_name ON \"{s}\".user_account (name)";
        yield return $"""
            CREATE TABLE "{s}".purchase (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id bigint NOT NULL REFERENCES "{s}".user_account (id),
                buy_date timestamptz NOT NULL)
            """;
        yield return $"CREATE INDEX ix_purchase_recent ON \"{s}\".purchase (user_id, buy_date DESC, id DESC)";
        yield return $"""
            CREATE TABLE "{s}".purchase_item (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                purchase_id bigint NOT NULL REFERENCES "{s}".purchase (id),
                product_id bigint NOT NULL REFERENCES "{s}".product (id),
                amount integer NOT NULL CHECK (amount > 0),
                price numeric(20, 2) NOT NULL)
            """;
        yield return $"CREATE INDEX ix_purchase_item_purchase ON \"{s}\".purchase_item (purchase_id)";
    }

    private static IEnumerable<string> SqlServer(string s)
    {
        yield return $"IF SCHEMA_ID(N'{s}') IS NULL EXEC(N'CREATE SCHEMA [{s}]')";
        yield return $"""
            CREATE TABLE [{s}].[product] (
                id bigint IDENTITY(1, 1) PRIMARY KEY,
                name nvarchar(1000) NOT NULL,
                price decimal(20, 2) NOT NULL,
                description nvarchar(max) NOT NULL,
                image varbinary(max) NULL)
            """;
        yield return $"CREATE INDEX ix_product_name ON [{s}].[product] (name)";
        yield return $"CREATE INDEX ix_product_price ON [{s}].[product] (price)";
        yield return $"""
            CREATE TABLE [{s}].[user_account] (
                id bigint IDENTITY(1, 1) PRIMARY KEY,
                user_name nvarchar(255) NOT NULL UNIQUE,
                password nvarchar(255) NOT NULL,
                name nvarchar(255) NOT NULL,
                roles nvarchar(255) NULL)
            """;
        yield return $"CREATE INDEX ix_user_name ON [{s}].[user_account] (name)";
        yield return $"""
            CREATE TABLE [{s}].[purchase] (
                id bigint IDENTITY(1, 1) PRIMARY KEY,
                user_id bigint NOT NULL REFERENCES [{s}].[user_account] (id),
                buy_date datetimeoffset NOT NULL)
            """;
        yield return $"CREATE INDEX ix_purchase_recent ON [{s}].[purchase] (user_id, buy_date DESC, id DESC)";
        yield return $"""
            CREATE TABLE [{s}].[purchase_item] (
                id bigint IDENTITY(1, 1) PRIMARY KEY,
                purchase_id bigint NOT NULL REFERENCES [{s}].[purchase] (id),
                product_id bigint NOT NULL REFERENCES [{s}].[product] (id),
                amount int NOT NULL CHECK (amount > 0),
                price decimal(20, 2) NOT NULL)
            """;
        yield return $"CREATE INDEX ix_purchase_item_purchase ON [{s}].[purchase_item] (purchase_id)";
    }
}

/// <summary>The demo data of the Kotlin version (users, products with images, two purchases of the admin).</summary>
public static class ShoppingDemoData
{
    public static async Task Load(ShoppingRepositories repositories, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(repositories);
        await repositories.Transactions.Required(async _ =>
        {
            var admin = await NewUser(repositories, "admin", "admin", "João da Silva", "Admin", cancellationToken);
            await NewUser(repositories, "fulano", "fulano", "Fulano de Tal", "Customer", cancellationToken);
            await NewUser(repositories, "beotrano", "beotrano", "Beotrano de Alguma Coisa", "Customer", cancellationToken);

            var coffee = await NewProduct(repositories, "Cafeteira design italiano", 199.99m, CoffeeMaker, "cafeteira.png", cancellationToken);
            var ball = await NewProduct(repositories, "Bola de vôlei", 45.30m, VolleyBall, "bola.png", cancellationToken);
            var tape = await NewProduct(repositories, "Fita veda rosca", 2.67m, ThreadTape, "vedarosca.png", cancellationToken);
            await NewProduct(repositories, "Pen Drive 2GB", 16.00m, PenDrive, "pendrive2gb.png", cancellationToken);

            await repositories.Purchases.Insert(new Purchase
            {
                User = admin,
                BuyDate = new DateTimeOffset(2010, 1, 1, 14, 30, 0, TimeSpan.Zero),
                Items = [new PurchaseItem { Product = coffee, Amount = 1, Price = 200.00m }],
            }, cancellationToken: cancellationToken);
            await repositories.Purchases.Insert(new Purchase
            {
                User = admin,
                BuyDate = new DateTimeOffset(2011, 4, 3, 9, 15, 0, TimeSpan.Zero),
                Items =
                [
                    new PurchaseItem { Product = ball, Amount = 1, Price = 45.30m },
                    new PurchaseItem { Product = tape, Amount = 1, Price = 2.67m },
                ],
            }, cancellationToken: cancellationToken);
        }, cancellationToken);
    }

    private static async Task<User> NewUser(ShoppingRepositories r, string login, string password, string name, string roles,
        CancellationToken cancellationToken)
    {
        var user = new User { UserName = login, Password = PasswordHash.Hash(password), Name = name, Roles = roles };
        await r.Users.Insert(user, cancellationToken: cancellationToken);
        return user;
    }

    private static async Task<Product> NewProduct(ShoppingRepositories r, string name, decimal price, string description,
        string image, CancellationToken cancellationToken)
    {
        var product = new Product { Name = name, Price = price, Description = description, Image = Image(image) };
        await r.Products.Insert(product, cancellationToken: cancellationToken);
        return product;
    }

    private static byte[] Image(string file)
    {
        using var stream = typeof(ShoppingDemoData).Assembly.GetManifestResourceStream($"Shopping.Persistence.Images.{file}")
                           ?? throw new InvalidOperationException($"Missing embedded image {file}.");
        using var buffer = new MemoryStream();
        stream.CopyTo(buffer);
        return buffer.ToArray();
    }

